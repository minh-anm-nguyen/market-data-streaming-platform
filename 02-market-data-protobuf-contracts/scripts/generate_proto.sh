#!/usr/bin/env bash
# Generate C++ and Python code from the ONE source of truth, plus the descriptor
# sets the schema gate compares against (section 12.2, NFR-10).
#
# Everything generated lands under build/ or python/src/md_contract/generated/
# and is reproducible from the schemas alone: nothing here is hand-edited, and
# `--check-stale` re-runs the generation into a scratch tree and diffs it, which
# is what catches "changed the .proto, forgot to regenerate" (K01, E08).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# MSYS2 ucrt64 carries the matched protoc + libprotobuf pair this project pins.
export PATH="/c/msys64/ucrt64/bin:$PATH"

PROTOC="${PROTOC:-protoc}"
PY_OUT_ROOT="python/src/md_contract/generated"
CPP_OUT_ROOT="cpp/generated"
DESC_DIR="build/descriptors"

# v1 is the release contract; the rest are evolution and negative fixtures that
# exist so the compatibility matrix and the schema gate have real binaries to
# run against rather than hypotheticals.
VARIANTS=(v1_1 v2_probe)

sha256() { sha256sum "$1" | cut -d' ' -f1; }

gen_one() {
  local name="$1" include="$2"
  local py="$PY_OUT_ROOT/$name" cpp="$CPP_OUT_ROOT/$name"
  mkdir -p "$py" "$cpp" "$DESC_DIR"
  "$PROTOC" -I "$include" \
    --python_out="$py" \
    --pyi_out="$py" \
    --cpp_out="$cpp" \
    --descriptor_set_out="$DESC_DIR/marketdata-$name.desc" \
    --include_imports \
    marketdata/v1/market_data.proto
  # Namespace packages would work on 3.3+, but explicit __init__.py keeps the
  # import path identical under pytest, a zipapp and a fresh venv (K03).
  find "$py" -type d -exec sh -c 'touch "$1/__init__.py"' _ {} \;
  echo "  $name -> $py, $cpp, $DESC_DIR/marketdata-$name.desc"
}

if [[ "${1:-}" == "--check-stale" ]]; then
  # Generate into a scratch tree and compare. A difference means the checked-in
  # generated code does not match the schemas.
  scratch="$(mktemp -d)"
  trap 'rm -rf "$scratch"' EXIT
  mkdir -p "$scratch/py" "$scratch/cpp"
  "$PROTOC" -I schemas --python_out="$scratch/py" --cpp_out="$scratch/cpp" \
    marketdata/v1/market_data.proto
  rc=0
  for f in marketdata/v1/market_data_pb2.py; do
    diff -q "$scratch/py/$f" "$PY_OUT_ROOT/v1/$f" >/dev/null 2>&1 || { echo "STALE: $f"; rc=1; }
  done
  for f in marketdata/v1/market_data.pb.cc marketdata/v1/market_data.pb.h; do
    diff -q "$scratch/cpp/$f" "$CPP_OUT_ROOT/v1/$f" >/dev/null 2>&1 || { echo "STALE: $f"; rc=1; }
  done
  [[ $rc -eq 0 ]] && echo "generated code is in sync with schemas"
  exit $rc
fi

echo "protoc: $("$PROTOC" --version)"
echo "generating:"
gen_one v1 schemas
for v in "${VARIANTS[@]}"; do gen_one "$v" "schemas/evolution/$v"; done

# Baseline descriptor for the release contract. The gate diffs candidate schemas
# against this file, so it is the thing that actually freezes the tag numbers.
mkdir -p toolchain/descriptor-baselines
cp "$DESC_DIR/marketdata-v1.desc" toolchain/descriptor-baselines/marketdata-v1.desc

# ---- toolchain lock -------------------------------------------------------
# Pinned so a build can be reproduced and so a gencode/runtime mismatch fails at
# build time rather than as a production incident (NFR-10, E05-E07).
PY="${PYTHON:-python}"
protoc_ver="$("$PROTOC" --version | awk '{print $2}')"
py_pb_ver="$("$PY" -c 'import google.protobuf as p; print(p.__version__)')"
py_ver="$("$PY" -c 'import sys; print("%d.%d.%d" % sys.version_info[:3])')"
py_impl="$("$PY" -c 'from google.protobuf.internal import api_implementation as a; print(a.Type())')"
cpp_pb_ver="$(pkg-config --modversion protobuf 2>/dev/null || echo UNKNOWN)"
cxx_ver="$(g++ --version | head -1)"

cat > toolchain/versions.lock <<LOCK
# Generated by scripts/generate_proto.sh -- do not hand-edit.
# A mismatch between any value here and the live toolchain is a build/deploy
# stop, not a warning: C++ protobuf gives no ABI guarantee across releases, so
# gencode and runtime must come from the same version (E05, E07).
protoc_version = "$protoc_ver"
cpp_protobuf_runtime_version = "$cpp_pb_ver"
python_protobuf_runtime_version = "$py_pb_ver"
python_protobuf_implementation = "$py_impl"
python_version = "$py_ver"
cxx_compiler = "$cxx_ver"
proto_v1_sha256 = "$(sha256 schemas/marketdata/v1/market_data.proto)"
descriptor_v1_sha256 = "$(sha256 toolchain/descriptor-baselines/marketdata-v1.desc)"
proto_v1_1_sha256 = "$(sha256 schemas/evolution/v1_1/marketdata/v1/market_data.proto)"
proto_v2_probe_sha256 = "$(sha256 schemas/evolution/v2_probe/marketdata/v1/market_data.proto)"
LOCK

echo
echo "toolchain/versions.lock:"
sed 's/^/  /' toolchain/versions.lock
