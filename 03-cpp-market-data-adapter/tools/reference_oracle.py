"""An independent reference model of the adapter's classification rules.

This exists to catch the failure mode where a test "passes" because the
expectation was generated by the implementation it is testing. It is written
from the design document, in a different language, with a deliberately naive
data structure (a plain dict of seen sequences rather than a ring buffer), so
that a bug in the C++ bounded-window arithmetic does not reproduce here.

It is NOT a second implementation to be kept in sync for its own sake: where
the two disagree, the design document decides which one is wrong.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Iterable

# Classification outcomes, matching the C++ SeqClass names.
OK = "OK"
GAP = "GAP"
DUPLICATE_EXACT = "DUPLICATE_EXACT"
DUPLICATE_CONFLICT = "DUPLICATE_CONFLICT"
REORDER_LATE = "REORDER_LATE"
TOO_OLD = "TOO_OLD_UNVERIFIABLE"
ROLLBACK = "SEQUENCE_ROLLBACK"


@dataclass
class Rules:
    price_scale: int
    min_price_ticks: int = 1
    max_price_ticks: int = 500000
    min_spread_ticks: int = 0
    max_spread_ticks: int = 200


DEFAULT_RULES = {
    "EURUSD": Rules(100000),
    "GBPUSD": Rules(100000),
    "USDJPY": Rules(1000),
}


@dataclass
class Decision:
    """What the reference model says should happen to one input event."""

    index: int
    stage: str  # structural | business | stream
    seq_class: str | None = None
    publish: bool = False
    reason: str = "none"
    flags: set[str] = field(default_factory=set)


def _core(ev: dict) -> tuple:
    """The typed core used for exact-duplicate comparison (design 5)."""
    if ev["kind"] == "quote":
        return ("quote", ev["event_time_ns"], ev["price_scale"],
                ev["bid_ticks"], ev["ask_ticks"])
    return ("tick", ev["event_time_ns"], ev["price_scale"], ev["price_ticks"], 0)


def validate_business(ev: dict, rules: dict[str, Rules]) -> str:
    """Returns 'none' or the rejection reason."""
    r = rules.get(ev["symbol"])
    if r is None:
        return "SYMBOL_NOT_ALLOWED"
    if ev["sequence"] <= 0:
        return "INVALID_SEQUENCE"
    if ev["event_time_ns"] < 0:
        return "NEGATIVE_EVENT_TIME"
    if ev["price_scale"] <= 0:
        return "INVALID_PRICE_SCALE"
    if ev["price_scale"] != r.price_scale:
        return "SCALE_MISMATCH"
    if ev["kind"] == "quote":
        bid, ask = ev["bid_ticks"], ev["ask_ticks"]
        if bid <= 0:
            return "QUOTE_BID_NON_POSITIVE"
        if ask < bid:
            return "QUOTE_CROSSED"
        if not (r.min_price_ticks <= bid <= r.max_price_ticks):
            return "PRICE_OUT_OF_RANGE"
        if not (r.min_price_ticks <= ask <= r.max_price_ticks):
            return "PRICE_OUT_OF_RANGE"
        if not (r.min_spread_ticks <= ask - bid <= r.max_spread_ticks):
            return "SPREAD_OUT_OF_RANGE"
    else:
        p = ev["price_ticks"]
        if p <= 0:
            return "TICK_NON_POSITIVE"
        if not (r.min_price_ticks <= p <= r.max_price_ticks):
            return "PRICE_OUT_OF_RANGE"
    return "none"


class ReferenceModel:
    def __init__(
        self,
        *,
        window: int = 4096,
        rules: dict[str, Rules] | None = None,
        mode: str = "strict_monitor",
        live: bool = False,
        expect_start_at_one: bool = False,
        event_time_stale_threshold_ns: int = 2_000_000_000,
    ) -> None:
        self.window = window
        self.rules = rules if rules is not None else DEFAULT_RULES
        self.mode = mode
        self.live = live
        self.expect_start_at_one = expect_start_at_one
        self.stale_ns = event_time_stale_threshold_ns
        # key -> {"high": int, "seen": {seq: core}, "watermark": int|None}
        self.keys: dict[tuple[str, str], dict] = {}

    def run(self, events: Iterable[dict]) -> list[Decision]:
        out: list[Decision] = []
        for i, ev in enumerate(events):
            out.append(self._one(i, ev))
        return out

    def published(self, events: Iterable[dict]) -> list[int]:
        """Sequences that should reach the sink, in order."""
        evs = list(events)
        return [
            evs[d.index]["sequence"]
            for d in self.run(evs)
            if d.publish
        ]

    def _one(self, index: int, ev: dict) -> Decision:
        d = Decision(index=index, stage="stream")
        br = validate_business(ev, self.rules)
        if br != "none":
            d.stage = "business"
            d.reason = br
            d.publish = False
            return d

        key = (ev["dataset_id"], ev["symbol"])
        st = self.keys.get(key)
        fault = self.mode == "fault_observe"

        if st is None:
            st = {"high": ev["sequence"], "seen": {}, "watermark": None}
            self.keys[key] = st
            st["seen"][ev["sequence"]] = _core(ev)
            d.seq_class = OK
            d.publish = True
            if self.expect_start_at_one and ev["sequence"] != 1:
                d.seq_class = GAP
                d.reason = "INITIAL_GAP"
                d.flags |= {"INITIAL_GAP", "GAP", "DEGRADED"}
            elif self.live:
                d.flags.add("START_UNVERIFIED")
                d.reason = "START_UNVERIFIED"
            self._freshness(ev, st, d, fault)
            return d

        high = st["high"]
        seq = ev["sequence"]
        lowest = high - self.window + 1

        if seq > high:
            if seq > high + 1:
                d.seq_class = GAP
                d.reason = "SEQUENCE_GAP"
                d.flags |= {"GAP", "DEGRADED"}
                if seq - high >= self.window:
                    d.flags.add("HUGE_GAP")
            else:
                d.seq_class = OK
            st["high"] = seq
            st["seen"][seq] = _core(ev)
            d.publish = True
        elif seq >= lowest:
            prev = st["seen"].get(seq)
            if prev is not None:
                if prev == _core(ev):
                    d.seq_class = DUPLICATE_EXACT
                    d.reason = "DUPLICATE_EXACT"
                    d.flags.add("DUPLICATE_EXACT")
                else:
                    d.seq_class = DUPLICATE_CONFLICT
                    d.reason = "DUPLICATE_CONFLICT"
                    d.flags |= {"DUPLICATE_CONFLICT", "DEGRADED"}
                d.publish = fault
            else:
                d.seq_class = REORDER_LATE
                d.reason = "REORDER_LATE"
                d.flags.add("REORDER_LATE")
                st["seen"][seq] = _core(ev)
                d.publish = fault
        elif seq == 1:
            d.seq_class = ROLLBACK
            d.reason = "SEQUENCE_ROLLBACK"
            d.flags |= {"SEQUENCE_ROLLBACK", "DEGRADED"}
            d.publish = True
        else:
            d.seq_class = TOO_OLD
            d.reason = "TOO_OLD_UNVERIFIABLE"
            d.flags.add("TOO_OLD_UNVERIFIABLE")
            d.publish = fault

        self._freshness(ev, st, d, fault)
        return d

    def _freshness(self, ev: dict, st: dict, d: Decision, fault: bool) -> None:
        """Event-time regression only. Quote inactivity is clock-driven and is
        covered by the virtual-clock tests rather than by this trace model."""
        wm = st["watermark"]
        if wm is not None and wm - ev["event_time_ns"] > self.stale_ns:
            d.flags |= {"EVENT_TIME_OLD", "DEGRADED"}
            if d.reason == "none":
                d.reason = "EVENT_TIME_OLD"
            if not fault:
                d.publish = False
            return
        if wm is None or ev["event_time_ns"] > wm:
            st["watermark"] = ev["event_time_ns"]
