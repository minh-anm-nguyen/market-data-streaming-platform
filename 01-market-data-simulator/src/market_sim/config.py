@dataclass(frozen=True)
class SimConfig:
    """Fully resolved, frozen configuration. A run never re-reads its source."""

    run: RunConfig
    symbol_order: tuple[str, ...]
    symbols: dict[str, SymbolConfig]
    file: FileOutputConfig
    tcp: TcpOutputConfig
    faults: FaultsConfig
    source_path: Path | None = None
    fault_plan_fingerprint: str = "none"
    _data_dict: dict[str, Any] = field(default_factory=dict, repr=False)
    _full_dict: dict[str, Any] = field(default_factory=dict, repr=False)

    @property
    def dataset_id(self) -> str:
        """Deterministic id over *data-affecting* config only.

        Changing the seed, t0, rate, symbol list or order, any symbol's price
        model, the quote ratio, the bound policy, the schema/generator version or
        the fault plan produces a different ``dataset_id`` (cases S07, S08).
        Changing queue sizes or ``scheduler_batch_ms`` does not.
        """
        return f"ds-{self.data_sha256[:16]}"

    @property
    def data_sha256(self) -> str:
        return hashlib.sha256(
            json.dumps(self._data_dict, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()

    @property
    def config_sha256(self) -> str:
        return hashlib.sha256(
            json.dumps(self._full_dict, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()

    def data_dict(self) -> dict[str, Any]:
        return json.loads(json.dumps(self._data_dict))

    def full_dict(self) -> dict[str, Any]:
        return json.loads(json.dumps(self._full_dict))

    def symbol(self, name: str) -> SymbolConfig:
        try:
            return self.symbols[name]
        except KeyError:
            raise ConfigError(
                f"unknown symbol {name!r}; allowlist is {list(self.symbol_order)}",
                code="CONFIG_UNKNOWN_SYMBOL",
                symbol=name,
            ) from None

    @property
    def total_weight(self) -> int:
        return sum(self.symbols[s].weight for s in self.symbol_order)

    def expected_slots(self) -> int | None:
        """Logical slot count, if the run is bounded by ``count`` or duration."""
        if self.run.count is not None:
            return self.run.count
        if self.run.duration_s is not None:
            return int(self.run.duration_s * self.run.rate_per_sec)
        return None


