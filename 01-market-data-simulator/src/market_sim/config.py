@lru_cache(maxsize=1)
def _static_environment() -> tuple[tuple[str, Any], ...]:
    """Platform facts, resolved once per process.

    ``platform.platform()`` measured at 2.4 s on its first call on Windows (it
    shells out for the OS version). It is called for both the manifest and the
    report, and a short run would otherwise spend most of its wall clock here.
    """
    return (
        ("python_version", platform.python_version()),
        ("python_implementation", platform.python_implementation()),
        ("platform", platform.platform()),
        ("machine", platform.machine()),
        ("processor", platform.processor() or "unknown"),
        ("cpu_count", os.cpu_count()),
        ("generator_version", GENERATOR_VERSION),
        ("schema_version", SCHEMA_VERSION),
    )


def runtime_fingerprint() -> dict[str, Any]:
    """Environment facts the run manifest must carry (NFR-10)."""
    return {**dict(_static_environment()), "argv": list(sys.argv)}


def _parse_run(table: dict[str, Any], overrides: dict[str, Any]) -> RunConfig:
    where = "run"
    _reject_unknown(table, _RUN_KEYS, where)
    merged = dict(table)
    # An override of ``None`` *clears* the key rather than being ignored. That is
    # what lets ``--count 5000`` on the command line replace a ``duration_s`` in
    # the file without tripping the mutual-exclusion check.
    for key, value in overrides.items():
        if value is None:
            merged.pop(key, None)
        else:
            merged[key] = value

    mode = _one_of(
        _as_str(_req(merged, "mode", where), "mode", where), "mode", where, MODES
    )
    seed = _in_range(
        _as_int(_req(merged, "seed", where), "seed", where), "seed", where, 0, 2**63 - 1
    )
    start_time_ns = _in_range(
        _as_int(_req(merged, "start_time_ns", where), "start_time_ns", where),
        "start_time_ns",
        where,
        0,
        2**62,
    )
    rate = _in_range(
        _as_int(_req(merged, "rate_per_sec", where), "rate_per_sec", where),
        "rate_per_sec",
        where,
        1,
        MAX_RATE_PER_SEC,
    )

    # count and duration_s are mutually exclusive (FR-06, case T14). "Present"
    # means present-and-not-null, so a template may carry an explicit null.
    has_count = merged.get("count") is not None
    has_duration = merged.get("duration_s") is not None
    if has_count and has_duration:
        raise ConfigError(
            "'count' and 'duration_s' are mutually exclusive; set exactly one",
            code="CONFIG_COUNT_DURATION_CONFLICT",
            section=where,
        )
    if not has_count and not has_duration:
        raise ConfigError(
            "exactly one of 'count' or 'duration_s' must be set in [run]",
            code="CONFIG_COUNT_DURATION_MISSING",
            section=where,
        )
    count: int | None = None
    duration_s: float | None = None
    if has_count:
        # count == 0 is legal and means "a complete, empty dataset" (case T03).
        count = _in_range(
            _as_int(merged["count"], "count", where), "count", where, 0, MAX_SEQUENCE
        )
    else:
        duration_s = _as_float(merged["duration_s"], "duration_s", where)
        if not (0 < duration_s <= 86_400 * 7):
            raise ConfigError(
                f"'duration_s' must be in (0, 604800], got {duration_s}",
                code="CONFIG_OUT_OF_RANGE",
                section=where,
                key="duration_s",
            )

    quote_ratio = _in_range(
        _as_int(_req(merged, "quote_ratio_pct", where), "quote_ratio_pct", where),
        "quote_ratio_pct",
        where,
        0,
        100,
    )
    batch_ms = _in_range(
        _as_int(_req(merged, "scheduler_batch_ms", where), "scheduler_batch_ms", where),
        "scheduler_batch_ms",
        where,
        1,
        10_000,
    )
    max_burst = _in_range(
        _as_int(_req(merged, "max_burst_slots", where), "max_burst_slots", where),
        "max_burst_slots",
        where,
        1,
        10_000_000,
    )
    max_lag = _in_range(
        _as_int(
            _req(merged, "max_scheduler_lag_ms", where), "max_scheduler_lag_ms", where
        ),
        "max_scheduler_lag_ms",
        where,
        1,
        3_600_000,
    )
    on_lag = _one_of(
        _as_str(_req(merged, "on_scheduler_lag", where), "on_scheduler_lag", where),
        "on_scheduler_lag",
        where,
        LAG_POLICIES,
    )
    bound_policy = _one_of(
        _as_str(_req(merged, "bound_policy", where), "bound_policy", where),
        "bound_policy",
        where,
        BOUND_POLICIES,
    )
    drain_timeout = _as_float(
        _req(merged, "shutdown_drain_timeout_s", where),
        "shutdown_drain_timeout_s",
        where,
    )
    if not (0 < drain_timeout <= 3600):
        raise ConfigError(
            f"'shutdown_drain_timeout_s' must be in (0, 3600], got {drain_timeout}",
            code="CONFIG_OUT_OF_RANGE",
            section=where,
            key="shutdown_drain_timeout_s",
        )

    return RunConfig(
        mode=mode,
        seed=seed,
        start_time_ns=start_time_ns,
        count=count,
        duration_s=duration_s,
        rate_per_sec=rate,
        quote_ratio_pct=quote_ratio,
        scheduler_batch_ms=batch_ms,
        max_burst_slots=max_burst,
        max_scheduler_lag_ms=max_lag,
        on_scheduler_lag=on_lag,
        bound_policy=bound_policy,
        shutdown_drain_timeout_s=drain_timeout,
    )


def _parse_file_output(table: dict[str, Any], base_dir: Path) -> FileOutputConfig:
    where = "output.file"
    _reject_unknown(table, _FILE_KEYS, where)
    enabled = _as_bool(_req(table, "enabled", where), "enabled", where)
    root_raw = Path(_as_str(_req(table, "root_dir", where), "root_dir", where))
    resolved_root = (
        root_raw.resolve() if root_raw.is_absolute() else (base_dir / root_raw).resolve()
    )

    def iv(key: str, lo: int, hi: int) -> int:
        return _in_range(_as_int(_req(table, key, where), key, where), key, where, lo, hi)

    # maxsize=0 means "unbounded" in asyncio.Queue; refuse it outright (case R01).
    max_queue_events = iv("max_queue_events", 1, 100_000_000)
    max_queue_bytes = iv("max_queue_bytes", 1024, 1 << 40)
    fsync_every_events = iv("fsync_every_events", 0, 1_000_000_000)
    fsync_every_seconds = _as_float(
        _req(table, "fsync_every_seconds", where), "fsync_every_seconds", where
    )
    if fsync_every_seconds < 0:
        raise ConfigError(
            "'fsync_every_seconds' must be >= 0 (0 disables time-based fsync)",
            code="CONFIG_OUT_OF_RANGE",
            section=where,
            key="fsync_every_seconds",
        )
    max_record_bytes = iv("max_record_bytes", MIN_RECORD_BYTES, 1 << 26)
    max_total_bytes = iv("max_total_bytes", 1024, 1 << 46)

    if max_queue_bytes < max_record_bytes:
        raise ConfigError(
            f"[{where}] max_queue_bytes ({max_queue_bytes}) is smaller than one "
            f"max_record_bytes ({max_record_bytes}): the queue could never accept "
            "a record",
            code="CONFIG_QUEUE_TOO_SMALL",
            section=where,
        )
    return FileOutputConfig(
        enabled=enabled,
        root_dir=resolved_root,
        max_queue_events=max_queue_events,
        max_queue_bytes=max_queue_bytes,
        fsync_every_events=fsync_every_events,
        fsync_every_seconds=fsync_every_seconds,
        max_record_bytes=max_record_bytes,
        max_total_bytes=max_total_bytes,
    )


def _parse_tcp_output(table: dict[str, Any]) -> TcpOutputConfig:
    where = "output.tcp"
    _reject_unknown(table, _TCP_KEYS, where)
    enabled = _as_bool(_req(table, "enabled", where), "enabled", where)
    host = _as_str(_req(table, "host", where), "host", where)
    port = _in_range(
        _as_int(_req(table, "port", where), "port", where), "port", where, 1, 65535
    )

    def iv(key: str, lo: int, hi: int) -> int:
        return _in_range(_as_int(_req(table, key, where), key, where), key, where, lo, hi)

    max_clients = iv("max_clients", 1, 1024)
    max_queue_events = iv("max_queue_events", 1, 100_000_000)
    max_queue_bytes = iv("max_queue_bytes", 1024, 1 << 40)
    send_timeout_ms = iv("send_timeout_ms", 1, 600_000)
    policy = _one_of(
        _as_str(_req(table, "slow_client_policy", where), "slow_client_policy", where),
        "slow_client_policy",
        where,
        SLOW_CLIENT_POLICIES,
    )
    wait_for_client = _as_bool(
        _req(table, "wait_for_client", where), "wait_for_client", where
    )
    startup_timeout_s = _as_float(
        _req(table, "startup_timeout_s", where), "startup_timeout_s", where
    )
    if not (0 < startup_timeout_s <= 3600):
        raise ConfigError(
            f"'startup_timeout_s' must be in (0, 3600], got {startup_timeout_s}; "
            "waiting for a client forever is not an option",
            code="CONFIG_OUT_OF_RANGE",
            section=where,
            key="startup_timeout_s",
        )
    allow_public_bind = _as_bool(
        _req(table, "allow_public_bind", where), "allow_public_bind", where
    )
    # NFR-09 / case N16: a non-loopback listener has to be opted into explicitly.
    if host not in _LOOPBACK_HOSTS and not allow_public_bind:
        raise ConfigError(
            f"refusing to bind non-loopback host {host!r} without "
            "output.tcp.allow_public_bind = true; this simulator has no "
            "authentication or TLS",
            code="CONFIG_PUBLIC_BIND_NOT_ALLOWED",
            section=where,
            host=host,
        )
    return TcpOutputConfig(
        enabled=enabled,
        host=host,
        port=port,
        max_clients=max_clients,
        max_queue_events=max_queue_events,
        max_queue_bytes=max_queue_bytes,
        send_timeout_ms=send_timeout_ms,
        slow_client_policy=policy,
        wait_for_client=wait_for_client,
        startup_timeout_s=startup_timeout_s,
        allow_public_bind=allow_public_bind,
    )


def _parse_faults(table: dict[str, Any], base_dir: Path) -> FaultsConfig:
    where = "faults"
    _reject_unknown(table, _FAULT_KEYS, where)
    enabled = _as_bool(_req(table, "enabled", where), "enabled", where)
    raw_path = table.get("plan_path")
    plan_path: Path | None = None
    if raw_path is not None:
        p = Path(_as_str(raw_path, "plan_path", where))
        plan_path = p.resolve() if p.is_absolute() else (base_dir / p).resolve()
    if enabled and plan_path is None:
        raise ConfigError(
            "faults.enabled = true requires faults.plan_path",
            code="CONFIG_FAULT_PLAN_MISSING",
            section=where,
        )
    return FaultsConfig(enabled=enabled, plan_path=plan_path)


def load_config(
    path: str | os.PathLike[str],
    *,
    overrides: dict[str, Any] | None = None,
    fault_plan_fingerprint: str = "none",
) -> SimConfig:
    """Load and validate a config file. Raises :class:`ConfigError` on anything odd."""
    cfg_path = Path(path).resolve()
    if not cfg_path.is_file():
        raise ConfigError(
            f"config file not found: {cfg_path}",
            code="CONFIG_FILE_NOT_FOUND",
            path=str(cfg_path),
        )
    try:
        raw = tomllib.loads(cfg_path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(
            f"invalid TOML in {cfg_path}: {exc}",
            code="CONFIG_TOML_SYNTAX",
            path=str(cfg_path),
        ) from exc
    except UnicodeDecodeError as exc:
        raise ConfigError(
            f"config file is not valid UTF-8: {cfg_path}",
            code="CONFIG_ENCODING",
            path=str(cfg_path),
        ) from exc
    return build_config(
        raw,
        base_dir=cfg_path.parent,
        source_path=cfg_path,
        overrides=overrides,
        fault_plan_fingerprint=fault_plan_fingerprint,
    )


def build_config(
    raw: dict[str, Any],
    *,
    base_dir: Path,
    source_path: Path | None = None,
    overrides: dict[str, Any] | None = None,
    fault_plan_fingerprint: str = "none",
) -> SimConfig:
    """Validate an already-parsed config mapping. Used directly by tests."""
    if not isinstance(raw, dict):
        raise ConfigError("config root must be a table", code="CONFIG_TYPE_ERROR")
    _reject_unknown(raw, _TOP_KEYS, "root")
    overrides = dict(overrides or {})

    run = _parse_run(_req(raw, "run", "root"), overrides)

    symbols_table = _req(raw, "symbols", "root")
    if not isinstance(symbols_table, dict):
        raise ConfigError(
            "[symbols] must be a table", code="CONFIG_TYPE_ERROR", section="symbols"
        )
    order_raw = _req(symbols_table, "order", "symbols")
    if not isinstance(order_raw, list) or not order_raw:
        raise ConfigError(
            "[symbols].order must be a non-empty array of symbol names",
            code="CONFIG_SYMBOL_ORDER_INVALID",
            section="symbols",
        )
    order: list[str] = []
    for item in order_raw:
        name = _as_str(item, "order[]", "symbols")
        if name in order:
            raise ConfigError(
                f"duplicate symbol {name!r} in [symbols].order",
                code="CONFIG_SYMBOL_DUPLICATE",
                symbol=name,
            )
        order.append(name)

    declared = {k: v for k, v in symbols_table.items() if k != "order"}
    missing = [s for s in order if s not in declared]
    if missing:
        raise ConfigError(
            f"symbols listed in order but not configured: {missing}",
            code="CONFIG_SYMBOL_UNDEFINED",
            missing=missing,
        )
    extra = sorted(set(declared) - set(order))
    if extra:
        raise ConfigError(
            f"symbol table(s) {extra} are not listed in [symbols].order; "
            "refusing to guess whether they should be generated",
            code="CONFIG_SYMBOL_NOT_IN_ORDER",
            extra=extra,
        )
    symbols = {name: _parse_symbol(name, declared[name]) for name in order}

    output_table = _req(raw, "output", "root")
    if not isinstance(output_table, dict):
        raise ConfigError(
            "[output] must be a table", code="CONFIG_TYPE_ERROR", section="output"
        )
    _reject_unknown(output_table, {"file", "tcp"}, "output")
    file_cfg = _parse_file_output(_req(output_table, "file", "output"), base_dir)
    tcp_cfg = _parse_tcp_output(_req(output_table, "tcp", "output"))
    faults_cfg = _parse_faults(_req(raw, "faults", "root"), base_dir)

    # Mode/sink coherence: a mode must never run with its sink switched off, and
    # must not quietly drive a sink the mode does not name.
    if run.mode in ("record", "both") and not file_cfg.enabled:
        raise ConfigError(
            f"mode={run.mode} requires output.file.enabled = true",
            code="CONFIG_MODE_SINK_CONFLICT",
            mode=run.mode,
        )
    if run.mode in ("serve", "both") and not tcp_cfg.enabled:
        raise ConfigError(
            f"mode={run.mode} requires output.tcp.enabled = true",
            code="CONFIG_MODE_SINK_CONFLICT",
            mode=run.mode,
        )
    if run.mode == "record" and tcp_cfg.enabled:
        raise ConfigError(
            "mode=record must not enable output.tcp; use mode=both to do both",
            code="CONFIG_MODE_SINK_CONFLICT",
            mode=run.mode,
        )
    if run.mode == "serve" and file_cfg.enabled:
        raise ConfigError(
            "mode=serve must not enable output.file; use mode=both to do both",
            code="CONFIG_MODE_SINK_CONFLICT",
            mode=run.mode,
        )

    planned = (
        run.count if run.count is not None else int((run.duration_s or 0) * run.rate_per_sec)
    )
    if planned > MAX_SEQUENCE:
        raise ConfigError(
            f"planned slot count {planned} exceeds the sequence ceiling {MAX_SEQUENCE}",
            code="CONFIG_SEQUENCE_CEILING",
            planned=planned,
        )

    data_dict = {
        "schema_version": SCHEMA_VERSION,
        "generator_version": GENERATOR_VERSION,
        "seed": run.seed,
        "start_time_ns": run.start_time_ns,
        "rate_per_sec": run.rate_per_sec,
        "count": run.count,
        "duration_s": run.duration_s,
        "quote_ratio_pct": run.quote_ratio_pct,
        "bound_policy": run.bound_policy,
        "symbol_order": list(order),
        "symbols": [symbols[s].as_data_dict() for s in order],
        "faults_enabled": faults_cfg.enabled,
        "fault_plan_fingerprint": fault_plan_fingerprint if faults_cfg.enabled else "none",
    }
    full_dict = {
        "data": data_dict,
        "run": {
            "mode": run.mode,
            "scheduler_batch_ms": run.scheduler_batch_ms,
            "max_burst_slots": run.max_burst_slots,
            "max_scheduler_lag_ms": run.max_scheduler_lag_ms,
            "on_scheduler_lag": run.on_scheduler_lag,
            "shutdown_drain_timeout_s": run.shutdown_drain_timeout_s,
        },
        "output_file": {
            "enabled": file_cfg.enabled,
            "max_queue_events": file_cfg.max_queue_events,
            "max_queue_bytes": file_cfg.max_queue_bytes,
            "fsync_every_events": file_cfg.fsync_every_events,
            "fsync_every_seconds": file_cfg.fsync_every_seconds,
            "max_record_bytes": file_cfg.max_record_bytes,
            "max_total_bytes": file_cfg.max_total_bytes,
        },
        "output_tcp": {
            "enabled": tcp_cfg.enabled,
            "host": tcp_cfg.host,
            "port": tcp_cfg.port,
            "max_clients": tcp_cfg.max_clients,
            "max_queue_events": tcp_cfg.max_queue_events,
            "max_queue_bytes": tcp_cfg.max_queue_bytes,
            "send_timeout_ms": tcp_cfg.send_timeout_ms,
            "slow_client_policy": tcp_cfg.slow_client_policy,
            "wait_for_client": tcp_cfg.wait_for_client,
            "startup_timeout_s": tcp_cfg.startup_timeout_s,
            "allow_public_bind": tcp_cfg.allow_public_bind,
        },
        "faults": {"enabled": faults_cfg.enabled},
    }

    return SimConfig(
        run=run,
        symbol_order=tuple(order),
        symbols=symbols,
        file=file_cfg,
        tcp=tcp_cfg,
        faults=faults_cfg,
        source_path=source_path,
        fault_plan_fingerprint=fault_plan_fingerprint,
        _data_dict=data_dict,
        _full_dict=full_dict,
    )


def safe_resolve_under(path: str | os.PathLike[str], roots: list[Path]) -> Path:
    """Resolve ``path`` and require it to live under one of ``roots``.

    Guards against ``../`` traversal and symlinks that escape the output sandbox
    (case C06). ``Path.resolve()`` expands symlinks, so containment is checked on
    the real path, not the spelling.
    """
    target = Path(path).resolve()
    for root in roots:
        root_resolved = root.resolve()
        if target == root_resolved or root_resolved in target.parents:
            return target
    raise ConfigError(
        f"path {target} is outside the allowed root(s) {[str(r) for r in roots]}",
        code="CONFIG_PATH_OUTSIDE_ROOT",
        path=str(target),
    )
