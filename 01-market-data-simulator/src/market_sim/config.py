"""Strict configuration: TOML load, validation, dataset identity, config hash.

Section 6 of SYSTEM_DESIGN. Design rules:

* **Unknown keys are errors**, at every level. A typo in a safety limit must not
  silently fall back to a default (case C01).
* Validation is **fail-fast and happens before any socket bind or file write**,
  so an invalid run cannot leave a half-built dataset behind (case E2E-11).
* ``dataset_id`` is derived only from fields that affect the *data*, so the same
  dataset can be regenerated byte-for-byte while operational knobs
  (``scheduler_batch_ms``, queue sizes, TCP settings) are free to change. That is
  what makes the determinism property in section 9.2 testable.
* ``config_sha256`` covers the *whole* resolved config, for the run manifest.
"""

