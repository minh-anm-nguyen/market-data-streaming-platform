#: Bumped whenever a change alters generated bytes for an unchanged config.
#: Part of ``dataset_id``, so old and new datasets can never be confused.
GENERATOR_VERSION: Final = "gen.1"

MODES: Final = ("record", "serve", "both", "replay", "verify", "benchmark")
RUNNING_MODES: Final = ("record", "serve", "both")

LAG_POLICIES: Final = ("continue-degraded", "fail-fast")
BOUND_POLICIES: Final = ("reflect", "clamp")
SLOW_CLIENT_POLICIES: Final = ("disconnect",)

#: Hard ceiling on ``sequence`` (case S10): refuse configs that could approach a
#: range where a consumer using IEEE754 doubles would lose precision, instead of
#: wrapping to 0.
MAX_SEQUENCE: Final = 2**53
MAX_RATE_PER_SEC: Final = 10_000_000
MIN_RECORD_BYTES: Final = 128


def _reject_unknown(table: dict[str, Any], allowed: set[str], where: str) -> None:
    unknown = sorted(set(table) - allowed)
    if unknown:
        raise ConfigError(
            f"unknown configuration key(s) in [{where}]: {', '.join(unknown)}",
            code="CONFIG_UNKNOWN_KEY",
            section=where,
            unknown=unknown,
            allowed=sorted(allowed),
        )


def _req(table: dict[str, Any], key: str, where: str) -> Any:
    if key not in table:
        raise ConfigError(
            f"missing required key '{key}' in [{where}]",
            code="CONFIG_MISSING_KEY",
            section=where,
            key=key,
        )
    return table[key]


def _as_int(value: Any, key: str, where: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ConfigError(
            f"'{key}' in [{where}] must be an integer, got {type(value).__name__}",
            code="CONFIG_TYPE_ERROR",
            section=where,
            key=key,
        )
    return value


def _as_bool(value: Any, key: str, where: str) -> bool:
    if not isinstance(value, bool):
        raise ConfigError(
            f"'{key}' in [{where}] must be a boolean, got {type(value).__name__}",
            code="CONFIG_TYPE_ERROR",
            section=where,
            key=key,
        )
    return value


def _as_str(value: Any, key: str, where: str) -> str:
    if not isinstance(value, str):
        raise ConfigError(
            f"'{key}' in [{where}] must be a string, got {type(value).__name__}",
            code="CONFIG_TYPE_ERROR",
            section=where,
            key=key,
        )
    return value


def _as_float(value: Any, key: str, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ConfigError(
            f"'{key}' in [{where}] must be a number, got {type(value).__name__}",
            code="CONFIG_TYPE_ERROR",
            section=where,
            key=key,
        )
    return float(value)


def _in_range(value: int, key: str, where: str, lo: int, hi: int) -> int:
    if not (lo <= value <= hi):
        raise ConfigError(
            f"'{key}' in [{where}] must be in [{lo}, {hi}], got {value}",
            code="CONFIG_OUT_OF_RANGE",
            section=where,
            key=key,
            value=value,
            min=lo,
            max=hi,
        )
    return value


def _one_of(value: str, key: str, where: str, choices: tuple[str, ...]) -> str:
    if value not in choices:
        raise ConfigError(
            f"'{key}' in [{where}] must be one of {list(choices)}, got {value!r}",
            code="CONFIG_INVALID_CHOICE",
            section=where,
            key=key,
            value=value,
        )
    return value


@dataclass(frozen=True, slots=True)
class SymbolConfig:
    """Per-symbol price model, all in integer ticks.

    ``price_scale`` is a *simulation* parameter (EURUSD 1e5, USDJPY 1e3 by the
    convention used here); it does not claim to match any particular broker.
    """

    symbol: str
    price_scale: int
    initial_price_ticks: int
    min_price_ticks: int
    max_price_ticks: int
    min_spread_ticks: int
    max_spread_ticks: int
    max_step_ticks: int
    weight: int

    def as_data_dict(self) -> dict[str, Any]:
        return {
            "symbol": self.symbol,
            "price_scale": self.price_scale,
            "initial_price_ticks": self.initial_price_ticks,
            "min_price_ticks": self.min_price_ticks,
            "max_price_ticks": self.max_price_ticks,
            "min_spread_ticks": self.min_spread_ticks,
            "max_spread_ticks": self.max_spread_ticks,
            "max_step_ticks": self.max_step_ticks,
            "weight": self.weight,
        }


_SYMBOL_KEYS: Final = {
    "price_scale",
    "initial_price_ticks",
    "min_price_ticks",
    "max_price_ticks",
    "min_spread_ticks",
    "max_spread_ticks",
    "max_step_ticks",
    "weight",
}


def _parse_symbol(name: str, table: Any) -> SymbolConfig:
    where = f"symbols.{name}"
    if not isinstance(table, dict):
        raise ConfigError(
            f"[{where}] must be a table", code="CONFIG_TYPE_ERROR", section=where
        )
    _reject_unknown(table, _SYMBOL_KEYS, where)
    if not is_valid_symbol(name):
        raise ConfigError(
            f"invalid symbol name {name!r}: must be {SYMBOL_MIN_LEN}-{SYMBOL_MAX_LEN} "
            "characters from A-Z 0-9 _ .",
            code="CONFIG_INVALID_SYMBOL",
            symbol=name,
        )

    def iv(key: str, lo: int, hi: int) -> int:
        return _in_range(_as_int(_req(table, key, where), key, where), key, where, lo, hi)

    price_scale = iv("price_scale", 1, 10**12)
    min_price = iv("min_price_ticks", 1, 2**62)
    max_price = iv("max_price_ticks", 1, 2**62)
    initial = iv("initial_price_ticks", 1, 2**62)
    min_spread = iv("min_spread_ticks", 0, 2**62)
    max_spread = iv("max_spread_ticks", 0, 2**62)
    max_step = iv("max_step_ticks", 0, 2**62)
    weight = iv("weight", 1, 1_000_000)

    if min_price > max_price:
        raise ConfigError(
            f"[{where}] min_price_ticks ({min_price}) > max_price_ticks ({max_price})",
            code="CONFIG_PRICE_RANGE_EMPTY",
            symbol=name,
        )
    if not (min_price <= initial <= max_price):
        raise ConfigError(
            f"[{where}] initial_price_ticks ({initial}) outside "
            f"[{min_price}, {max_price}]",
            code="CONFIG_INITIAL_PRICE_OUT_OF_RANGE",
            symbol=name,
        )
    if min_spread > max_spread:
        raise ConfigError(
            f"[{where}] min_spread_ticks ({min_spread}) > max_spread_ticks "
            f"({max_spread})",
            code="CONFIG_SPREAD_RANGE_EMPTY",
            symbol=name,
        )
    # A quote must fit inside the price band once the spread is applied, or the
    # generator could not keep bid >= min_price and ask <= max_price at the same
    # time. Catching it here means the invariant checker can never see it.
    if max_spread > max_price - min_price:
        raise ConfigError(
            f"[{where}] max_spread_ticks ({max_spread}) does not fit in the price "
            f"band of width {max_price - min_price}",
            code="CONFIG_SPREAD_EXCEEDS_BAND",
            symbol=name,
        )
    return SymbolConfig(
        symbol=name,
        price_scale=price_scale,
        initial_price_ticks=initial,
        min_price_ticks=min_price,
        max_price_ticks=max_price,
        min_spread_ticks=min_spread,
        max_spread_ticks=max_spread,
        max_step_ticks=max_step,
        weight=weight,
    )


