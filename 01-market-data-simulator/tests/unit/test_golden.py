"""Golden fixture comparison (milestone M0, cases S06, C10).

These files are the frozen contract for Project 03's C++ adapter. A change in
generated bytes has to be a deliberate act: regenerate with
``scripts/make_golden.py`` and bump ``GENERATOR_VERSION`` in the same commit.

Determinism within one runtime is proven by the end-to-end tests. What this adds
is determinism *across commits*, which is what makes a fixture a fixture.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from conftest import config_dict
from market_sim.config import GENERATOR_VERSION, build_config
from market_sim.engine import run_simulation
from market_sim.faults import parse_fault_plan
from market_sim.model import SCHEMA_VERSION, parse_canonical_line
from market_sim.prng import ALGORITHM
from market_sim.recorder import EVENTS_NAME, FAULT_MANIFEST_NAME
from market_sim.verify import iter_lines

GOLDEN_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "golden"
INDEX = GOLDEN_DIR / "index.json"


def load_index() -> dict:
    if not INDEX.is_file():
        pytest.skip(f"no golden fixtures; run scripts/make_golden.py ({INDEX})")
    return json.loads(INDEX.read_text(encoding="utf-8"))


def case_ids() -> list[str]:
    if not INDEX.is_file():
        return []
    return [c["name"] for c in json.loads(INDEX.read_text(encoding="utf-8"))["cases"]]


def config_for(case: dict, tmp_path: Path):
    plan = parse_fault_plan({"fault": case["faults"]})
    cfg = build_config(
        config_dict(
            mode="record",
            count=case["count"],
            rate=1_000_000,
            faults_enabled=bool(case["faults"]),
            plan_path="plan.toml" if case["faults"] else None,
        ),
        base_dir=tmp_path,
        fault_plan_fingerprint=plan.fingerprint() if case["faults"] else "none",
    )
    return cfg, plan


def sequences(path: Path) -> dict[str, list[int]]:
    out: dict[str, list[int]] = {}
    for _, raw, had_newline in iter_lines(path, max_line_bytes=4096):
        assert had_newline, f"{path} ends mid-record"
        event = parse_canonical_line(raw)
        out.setdefault(event.symbol, []).append(event.sequence)
    return out


class TestFixtureIntegrity:
    def test_the_index_pins_the_versions_the_bytes_depend_on(self):
        index = load_index()
        assert index["generator_version"] == GENERATOR_VERSION, (
            "the golden fixtures came from a different generator version; "
            "regenerate them deliberately with scripts/make_golden.py"
        )
        assert index["schema_version"] == SCHEMA_VERSION
        assert index["prng"] == ALGORITHM

    def test_each_fixture_file_matches_its_recorded_hash(self):
        # Guards the fixtures themselves against bit rot or a bad merge.
        for case in load_index()["cases"]:
            body = (GOLDEN_DIR / case["name"] / EVENTS_NAME).read_bytes()
            assert hashlib.sha256(body).hexdigest() == case["events_sha256"], case["name"]
            assert len(body) == case["events_bytes"]
            assert body.count(b"\n") == case["events_lines"]

    def test_the_three_milestone_cases_are_present(self):
        # M0 asks for a clean dataset, one with gaps and duplicates, and one
        # with stale timestamps and a reorder.
        assert set(case_ids()) == {"normal", "gaps_duplicates", "stale_reorder"}


@pytest.mark.parametrize("name", case_ids())
class TestRegeneration:
    def _case(self, name: str) -> dict:
        return next(c for c in load_index()["cases"] if c["name"] == name)

    async def test_regenerating_reproduces_the_golden_bytes(self, tmp_path, name):
        case = self._case(name)
        cfg, plan = config_for(case, tmp_path)
        result = await run_simulation(cfg, fault_plan=plan)
        assert result.ok, result.report.get("error")

        produced = (result.run_dir / EVENTS_NAME).read_bytes()
        assert hashlib.sha256(produced).hexdigest() == case["events_sha256"], (
            f"{name}: generated bytes no longer match the golden fixture. If the "
            "change is intended, run scripts/make_golden.py and bump "
            "GENERATOR_VERSION in the same commit."
        )
        assert produced == (GOLDEN_DIR / name / EVENTS_NAME).read_bytes()

    async def test_the_dataset_identity_is_also_stable(self, tmp_path, name):
        # dataset_id is what a downstream consumer keys on, so it is pinned too.
        case = self._case(name)
        cfg, _plan = config_for(case, tmp_path)
        assert cfg.dataset_id == case["dataset_id"]
        assert cfg.data_sha256 == case["data_sha256"]
        assert cfg.fault_plan_fingerprint == case["fault_plan_fingerprint"]

    async def test_the_recorded_counts_are_stable(self, tmp_path, name):
        case = self._case(name)
        cfg, plan = config_for(case, tmp_path)
        result = await run_simulation(cfg, fault_plan=plan)
        counts = result.report["counts"]
        for key in (
            "logical_slots",
            "emitted_events",
            "intentional_omissions",
            "intentional_duplicates",
            "recorded_events",
        ):
            assert counts[key] == case["counts"][key], f"{name}.{key}"


class TestGoldenFixtureSemantics:
    """The fixtures must actually contain the anomalies they advertise.

    Without this a fixture could be byte-stable and still useless: a
    gap-detection fixture with no gap in it would let a broken adapter pass.
    """

    def test_the_clean_fixture_has_no_anomalies(self):
        for symbol, seqs in sequences(GOLDEN_DIR / "normal" / EVENTS_NAME).items():
            assert seqs == list(range(1, len(seqs) + 1)), symbol

    def test_the_gap_fixture_really_has_a_gap_and_duplicates(self):
        seen = sequences(GOLDEN_DIR / "gaps_duplicates" / EVENTS_NAME)
        assert 100 not in seen["EURUSD"]
        assert 99 in seen["EURUSD"] and 101 in seen["EURUSD"]
        assert seen["GBPUSD"].count(50) == 2
        assert seen["USDJPY"].count(20) == 2

    def test_the_conflicting_duplicate_has_two_different_payloads(self):
        path = GOLDEN_DIR / "gaps_duplicates" / EVENTS_NAME
        lines = [
            raw
            for _, raw, _ in iter_lines(path, max_line_bytes=4096)
            if b'"sequence":20,' in raw and b"USDJPY" in raw
        ]
        assert len(lines) == 2
        assert lines[0] != lines[1]

    def test_the_stale_fixture_has_a_backwards_timestamp_and_a_reorder(self):
        path = GOLDEN_DIR / "stale_reorder" / EVENTS_NAME
        jpy: dict[int, int] = {}
        eur_order: list[int] = []
        for _, raw, _ in iter_lines(path, max_line_bytes=4096):
            event = parse_canonical_line(raw)
            if event.symbol == "USDJPY":
                jpy[event.sequence] = event.event_time_ns
            elif event.symbol == "EURUSD":
                eur_order.append(event.sequence)
        assert jpy[30] < jpy[29], "the stale_timestamp fault is not visible"
        index = eur_order.index(60)
        assert eur_order[index - 1] == 61, "the reorder fault is not visible"

    def test_each_faulted_fixture_ships_its_manifest(self):
        for name in ("gaps_duplicates", "stale_reorder"):
            path = GOLDEN_DIR / name / FAULT_MANIFEST_NAME
            assert path.is_file(), name
            rows = [
                json.loads(line)
                for line in path.read_text(encoding="utf-8").splitlines()
                if line.strip()
            ]
            assert rows
            for row in rows:
                assert row["planned"] is True
                if not row["applied"]:
                    assert row["reason_if_not_applied"], row["fault_id"]

    def test_the_clean_fixture_ships_no_manifest(self):
        # No faults, so no answer key -- and nothing to mistake for one.
        assert not (GOLDEN_DIR / "normal" / FAULT_MANIFEST_NAME).exists()


class TestConfigAndPlanMustAgree:
    """dataset_id folds in the plan fingerprint, so the two must match.

    Without this, a run could apply eight faults while its manifest recorded
    ``fault_plan_fingerprint: none`` and its dataset_id claimed the data was
    clean -- which is exactly the collision the fingerprint exists to prevent
    (cases S07, S08).
    """

    def _cfg(self, tmp_path, *, enabled=True, fingerprint="none"):
        return build_config(
            config_dict(
                mode="record",
                count=50,
                rate=1_000_000,
                faults_enabled=enabled,
                plan_path="plan.toml" if enabled else None,
            ),
            base_dir=tmp_path,
            fault_plan_fingerprint=fingerprint,
        )

    def test_a_missing_fingerprint_is_refused(self, tmp_path):
        from market_sim.engine import SimulatorEngine
        from market_sim.errors import ConfigError

        plan = parse_fault_plan(
            {"fault": [{"kind": "missing_sequence", "symbol": "EURUSD", "sequence": 10}]}
        )
        with pytest.raises(ConfigError) as exc:
            SimulatorEngine(self._cfg(tmp_path), fault_plan=plan)
        assert exc.value.code == "CONFIG_FAULT_FINGERPRINT_MISMATCH"

    def test_a_fingerprint_from_a_different_plan_is_refused(self, tmp_path):
        from market_sim.engine import SimulatorEngine
        from market_sim.errors import ConfigError

        planned = parse_fault_plan(
            {"fault": [{"kind": "missing_sequence", "symbol": "EURUSD", "sequence": 10}]}
        )
        other = parse_fault_plan(
            {"fault": [{"kind": "missing_sequence", "symbol": "EURUSD", "sequence": 11}]}
        )
        cfg = self._cfg(tmp_path, fingerprint=other.fingerprint())
        with pytest.raises(ConfigError) as exc:
            SimulatorEngine(cfg, fault_plan=planned)
        assert exc.value.code == "CONFIG_FAULT_FINGERPRINT_MISMATCH"
        assert exc.value.context["plan_fingerprint"] == planned.fingerprint()

    def test_a_plan_with_faults_disabled_is_refused(self, tmp_path):
        from market_sim.engine import SimulatorEngine
        from market_sim.errors import ConfigError

        plan = parse_fault_plan(
            {"fault": [{"kind": "missing_sequence", "symbol": "EURUSD", "sequence": 10}]}
        )
        with pytest.raises(ConfigError) as exc:
            SimulatorEngine(self._cfg(tmp_path, enabled=False), fault_plan=plan)
        assert exc.value.code == "CONFIG_FAULT_PLAN_IGNORED"

    def test_matching_fingerprints_are_accepted(self, tmp_path):
        from market_sim.engine import SimulatorEngine

        plan = parse_fault_plan(
            {"fault": [{"kind": "missing_sequence", "symbol": "EURUSD", "sequence": 10}]}
        )
        engine = SimulatorEngine(
            self._cfg(tmp_path, fingerprint=plan.fingerprint()), fault_plan=plan
        )
        assert engine.injector.enabled is True

    def test_a_clean_run_needs_no_fingerprint(self, tmp_path):
        from market_sim.engine import SimulatorEngine

        engine = SimulatorEngine(self._cfg(tmp_path, enabled=False))
        assert engine.injector.enabled is False
