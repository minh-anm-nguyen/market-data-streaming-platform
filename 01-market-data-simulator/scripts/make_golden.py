"""Regenerate the golden fixtures in tests/fixtures/golden.

Run this only when a change is *intended* to alter generated bytes, and bump
GENERATOR_VERSION in the same commit. ``tests/unit/test_golden.py`` compares
against these files, so an unintended change fails there instead of quietly
propagating into every downstream fixture.

    python scripts/make_golden.py
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

from conftest import config_dict  # noqa: E402
from market_sim.config import build_config  # noqa: E402
from market_sim.engine import run_simulation  # noqa: E402
from market_sim.faults import parse_fault_plan  # noqa: E402
from market_sim.recorder import EVENTS_NAME, FAULT_MANIFEST_NAME  # noqa: E402

GOLDEN_DIR = ROOT / "tests" / "fixtures" / "golden"

#: The three datasets milestone M0 asks for: a clean one, one with gaps and
#: duplicates, and one with stale timestamps and a reorder.
CASES = {
    "normal": {"count": 500, "faults": []},
    "gaps_duplicates": {
        "count": 500,
        "faults": [
            {"kind": "missing_sequence", "symbol": "EURUSD", "sequence": 100},
            {"kind": "duplicate_exact", "symbol": "GBPUSD", "sequence": 50},
            {"kind": "duplicate_conflict", "symbol": "USDJPY", "sequence": 20},
        ],
    },
    "stale_reorder": {
        "count": 500,
        "faults": [
            {
                "kind": "stale_timestamp",
                "symbol": "USDJPY",
                "sequence": 30,
                "offset_ms": 2000,
            },
            {"kind": "reorder_adjacent", "symbol": "EURUSD", "sequence": 60},
            {"kind": "timestamp_future", "symbol": "GBPUSD", "sequence": 40, "offset_ms": 500},
            {"kind": "invalid_spread", "symbol": "EURUSD", "sequence": 90},
        ],
    },
}


async def build_case(name: str, spec: dict) -> dict:
    plan = parse_fault_plan({"fault": spec["faults"]})
    with tempfile.TemporaryDirectory() as tmp:
        raw = config_dict(
            mode="record",
            count=spec["count"],
            rate=1_000_000,
            faults_enabled=bool(spec["faults"]),
            plan_path="plan.toml" if spec["faults"] else None,
        )
        cfg = build_config(
            raw,
            base_dir=Path(tmp),
            fault_plan_fingerprint=plan.fingerprint() if spec["faults"] else "none",
        )
        result = await run_simulation(cfg, fault_plan=plan)
        if not result.ok:
            raise SystemExit(f"{name}: run failed: {result.report.get('error')}")

        target = GOLDEN_DIR / name
        target.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(result.run_dir / EVENTS_NAME, target / EVENTS_NAME)
        manifest_src = result.run_dir / FAULT_MANIFEST_NAME
        if manifest_src.is_file():
            shutil.copyfile(manifest_src, target / FAULT_MANIFEST_NAME)

        body = (target / EVENTS_NAME).read_bytes()
        return {
            "name": name,
            "dataset_id": cfg.dataset_id,
            "data_sha256": cfg.data_sha256,
            "fault_plan_fingerprint": cfg.fault_plan_fingerprint,
            "count": spec["count"],
            "faults": spec["faults"],
            "events_sha256": hashlib.sha256(body).hexdigest(),
            "events_bytes": len(body),
            "events_lines": body.count(b"\n"),
            "counts": result.report["counts"],
        }


async def main() -> None:
    GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
    index = {
        "note": (
            "Golden fixtures. Regenerate with scripts/make_golden.py only when a "
            "byte change is intended, and bump GENERATOR_VERSION in the same commit."
        ),
        "generator_version": __import__("market_sim.config", fromlist=["x"]).GENERATOR_VERSION,
        "schema_version": __import__("market_sim.model", fromlist=["x"]).SCHEMA_VERSION,
        "prng": __import__("market_sim.prng", fromlist=["x"]).ALGORITHM,
        "cases": [await build_case(name, spec) for name, spec in CASES.items()],
    }
    (GOLDEN_DIR / "index.json").write_text(
        json.dumps(index, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    for case in index["cases"]:
        print(f"{case['name']:18s} {case['events_lines']:>6} lines  {case['events_sha256']}")


if __name__ == "__main__":
    asyncio.run(main())
