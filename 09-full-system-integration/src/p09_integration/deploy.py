"""M2/M3: render the init jobs from the lock, and judge what they produced.

The init jobs are **generated from** ``contracts.lock.yaml`` rather than written
by hand. That is the point: a topic created with 4 partitions by a script nobody
re-read would break per-key ordering silently, and P09 FR-03 asks for the
opposite -- provisioning that cannot disagree with the contract because it is
derived from it.

Three properties the generated scripts hold to:

* **Idempotent.** Creating a topic that exists, or applying DDL that exists, is
  a no-op and exits zero. Re-running the stack is a supported operation, not a
  recovery procedure.
* **Create then verify, as separate claims.** ``kafka-topics --create``
  succeeding does not establish that the topic has the partition count the
  contract wants: it may have existed already with the wrong shape. So every
  create is followed by a describe, and the describe is what decides (FR-03's
  "post-init contract validator").
* **The DDL is the projects' own files, by path.** Nothing is copied or inlined.
  P05 owns the raw table and P06 owns the analytics objects; a second copy of
  their SQL here would be another instance of the duplication the audit already
  found (P09-M0-02).

The scripts run where the Docker daemon is, which on this machine is inside WSL,
so they are plain POSIX shell with no Python dependency and reach the services
through ``docker exec``. WSL's localhost forwarding does not bridge these ports
to Windows, and a script assuming it did would fail in a way that looks like a
broken broker.

:func:`render_init` writes the scripts; :func:`compare_infra` judges what they
observed. Keeping those apart means a script cannot mark its own work.
"""

from __future__ import annotations

import datetime as _dt
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

#: The DDL each project owns, applied in this order. Order matters: a database
#: before its tables, and the materialized view after both tables it touches.
DDL_SOURCES: tuple[tuple[str, str], ...] = (
    ("P05", "05-python-batch-ingestion/sql/001_create_raw_table.sql"),
    ("P06", "06-clickhouse-analytics/sql/001_database.sql"),
    ("P06", "06-clickhouse-analytics/sql/002_canonical_ticks.sql"),
    ("P06", "06-clickhouse-analytics/sql/003_bars_1m_state.sql"),
    ("P06", "06-clickhouse-analytics/sql/004_mv_canonical_to_bars.sql"),
)

KAFKA_CONTAINER = "p09-dev-kafka"
CLICKHOUSE_CONTAINER = "p09-dev-clickhouse"
DEFAULT_REPO_MOUNT = "/mnt/d/trading/prj-3"

_PREAMBLE = """#!/bin/sh
# GENERATED by `p09 render-init` from contracts.lock.yaml. Do not hand-edit:
# the next render overwrites it, and a hand-edited init job is exactly the drift
# this file exists to prevent.
#
# Lock cut at:      {generated_at}
# Schema identity:  {schema_identity}
set -eu
"""


class DeployError(RuntimeError):
    """The lock does not carry something an init job needs."""


@dataclass(frozen=True)
class InfraExpectation:
    """What the lock says the deployed infrastructure must look like."""

    topics: tuple[str, ...]
    partitions_per_topic: int
    cleanup_policy: str
    allow_auto_topic_create: bool
    tables: tuple[str, ...]

    @classmethod
    def from_lock(cls, lock: dict[str, Any]) -> "InfraExpectation":
        cross = lock.get("cross_project_identity") or {}
        kafka = cross.get("kafka") or {}
        clickhouse = cross.get("clickhouse") or {}

        topics = tuple(
            t for t in (kafka.get("ticks_topic"), kafka.get("quotes_topic")) if t
        )
        tables = tuple(
            t
            for t in (
                clickhouse.get("raw_table"),
                clickhouse.get("canonical_table"),
                clickhouse.get("bars_table"),
            )
            if t
        )
        partitions = kafka.get("partitions_per_topic")
        policy = kafka.get("cleanup_policy")

        missing: list[str] = []
        if len(topics) != 2:
            missing.append("kafka.ticks_topic / kafka.quotes_topic")
        if not isinstance(partitions, int):
            missing.append("kafka.partitions_per_topic")
        if not policy:
            missing.append("kafka.cleanup_policy")
        if len(tables) != 3:
            missing.append("clickhouse.raw_table / canonical_table / bars_table")
        if missing:
            raise DeployError(
                "lock is missing values the init jobs need: " + ", ".join(missing)
            )

        return cls(
            topics=topics,
            partitions_per_topic=int(partitions),
            cleanup_policy=str(policy),
            allow_auto_topic_create=bool(kafka.get("allow_auto_topic_create")),
            tables=tables,
        )


def _utc_now() -> str:
    return (
        _dt.datetime.now(_dt.UTC)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def _preamble(lock: dict[str, Any]) -> str:
    schema = (lock.get("cross_project_identity") or {}).get("wire_schema") or {}
    return _PREAMBLE.format(
        generated_at=lock.get("generated_at_utc", "unknown"),
        schema_identity=schema.get("normalized_sha256", "unknown"),
    )


_PARTITION_AWK = (
    "awk '/PartitionCount/ {for (i = 1; i <= NF; i++) "
    'if ($i == "PartitionCount:") print $(i + 1)}\''
)
_REPLICATION_AWK = (
    "awk '/ReplicationFactor/ {for (i = 1; i <= NF; i++) "
    'if ($i == "ReplicationFactor:") print $(i + 1)}\''
)


def _render_topics(lock: dict[str, Any], expect: InfraExpectation) -> str:
    lines = [
        _preamble(lock),
        "# P09 M3: idempotent topic provisioning, then a describe that decides.",
        "#",
        "# --if-not-exists makes a re-run a no-op. It also means a topic that",
        "# already exists with the WRONG shape is left alone and still reported",
        "# as created, so the create step cannot be the check. The describe is.",
        "",
        'CONTAINER="${CONTAINER:-%s}"' % KAFKA_CONTAINER,
        'KAFKA_BIN="${KAFKA_BIN:-/opt/kafka/bin}"',
        'BOOTSTRAP="${BOOTSTRAP:-localhost:9092}"',
        "PARTITIONS=%d" % expect.partitions_per_topic,
        'REPLICATION="${REPLICATION:-1}"',
        'CLEANUP="%s"' % expect.cleanup_policy,
        "",
        "kt() {",
        '  docker exec -i "$CONTAINER" "$KAFKA_BIN/kafka-topics.sh" \\',
        '    --bootstrap-server "$BOOTSTRAP" "$@"',
        "}",
        "",
        'echo "== create =="',
    ]
    for topic in expect.topics:
        lines.extend(
            [
                'kt --create --if-not-exists --topic "%s" \\' % topic,
                '  --partitions "$PARTITIONS" --replication-factor "$REPLICATION" \\',
                '  --config "cleanup.policy=$CLEANUP" \\',
                "  --config unclean.leader.election.enable=false",
                'echo "  requested %s"' % topic,
            ]
        )

    lines.extend(["", 'echo "== verify =="', "rc=0"])
    for topic in expect.topics:
        lines.extend(
            [
                'actual=$(kt --describe --topic "%s" | %s)' % (topic, _PARTITION_AWK),
                'if [ "$actual" = "$PARTITIONS" ]; then',
                '  echo "  ok   %s partitions=$actual"' % topic,
                "else",
                '  echo "  FAIL %s partitions=$actual expected=$PARTITIONS" >&2'
                % topic,
                "  rc=1",
                "fi",
            ]
        )

    lines.extend(
        [
            "",
            "# FR-03: auto-creation must stay off. With it on, a typo in a",
            "# consumer group silently manufactures a 1-partition topic and the",
            "# ordering contract is gone with no error raised anywhere.",
            'auto=$(docker exec -i "$CONTAINER" "$KAFKA_BIN/kafka-configs.sh" \\',
            '  --bootstrap-server "$BOOTSTRAP" --entity-type brokers \\',
            "  --entity-default --describe 2>/dev/null \\",
            "  | grep -c 'auto.create.topics.enable=true' || true)",
            'if [ "$auto" -gt 0 ]; then',
            '  echo "  FAIL a broker default re-enables topic auto-creation" >&2',
            "  rc=1",
            "else",
            '  echo "  ok   no broker default enabling auto-creation"',
            "fi",
            "",
            'exit "$rc"',
            "",
        ]
    )
    return "\n".join(lines)


def _render_ddl(lock: dict[str, Any], root: Path) -> str:
    lines = [
        _preamble(lock),
        "# P09 M3: apply the DDL each project owns, in dependency order.",
        "#",
        "# The SQL is NOT copied here. These are the projects' own files read by",
        "# path, so there is one source of truth per object. Every statement is",
        "# CREATE ... IF NOT EXISTS, which is what makes a re-run a no-op.",
        "#",
        "# Nothing here ALTERs anything. A program that can reshape its own sink",
        "# can hide a schema mismatch from the operator, so a table that exists",
        "# with the wrong shape must fail the verify step, not be repaired here.",
        "",
        'REPO="${REPO:-%s}"' % DEFAULT_REPO_MOUNT,
        'CONTAINER="${CONTAINER:-%s}"' % CLICKHOUSE_CONTAINER,
        "",
        "apply() {",
        '  path="$REPO/$1"',
        '  if [ ! -f "$path" ]; then',
        '    echo "  FAIL missing DDL: $path" >&2',
        "    return 1",
        "  fi",
        '  docker exec -i "$CONTAINER" clickhouse-client --multiquery < "$path"',
        '  echo "  applied $1"',
        "}",
        "",
        'echo "== apply DDL =="',
    ]
    for owner, relative in DDL_SOURCES:
        absent = "" if (root / relative).exists() else "  # ABSENT at render time"
        lines.append('apply "%s"  # owner %s%s' % (relative, owner, absent))
    lines.extend(["", 'echo "DDL applied"', ""])
    return "\n".join(lines)


def _render_verify(lock: dict[str, Any], expect: InfraExpectation) -> str:
    """Emit a JSON report of what is deployed. Judges nothing, deliberately."""
    lines = [
        _preamble(lock),
        "# P09 M3 post-init observation. This script REPORTS; it does not judge.",
        "# `p09 verify-infra` compares the report against the lock, so the thing",
        "# measured is never the thing deciding whether it passed.",
        "#",
        "# Every field it cannot read comes out null or empty rather than as a",
        "# plausible default: unknown and zero are different answers (NFR-07).",
        "",
        'CONTAINER_KAFKA="${CONTAINER_KAFKA:-%s}"' % KAFKA_CONTAINER,
        'CONTAINER_CH="${CONTAINER_CH:-%s}"' % CLICKHOUSE_CONTAINER,
        'KAFKA_BIN="${KAFKA_BIN:-/opt/kafka/bin}"',
        'BOOTSTRAP="${BOOTSTRAP:-localhost:9092}"',
        'TOPICS="%s"' % " ".join(expect.topics),
        'TABLES="%s"' % " ".join(expect.tables),
        "",
        'cluster_id=$(docker exec -i "$CONTAINER_KAFKA" "$KAFKA_BIN/kafka-cluster.sh" \\',
        '  cluster-id --bootstrap-server "$BOOTSTRAP" 2>/dev/null \\',
        "  | sed -n 's/^Cluster ID: //p' || true)",
        'ch_version=$(docker exec -i "$CONTAINER_CH" clickhouse-client \\',
        "  --query 'SELECT version()' 2>/dev/null || true)",
        "",
        "printf '{\\n'",
        'printf \'  "generated_at_utc": "%s",\\n\' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"',
        'printf \'  "cluster_id": "%s",\\n\' "$cluster_id"',
        'printf \'  "clickhouse_version": "%s",\\n\' "$ch_version"',
        "",
        "printf '  \"topics\": ['",
        "first=1",
        'for t in $TOPICS; do',
        '  desc=$(docker exec -i "$CONTAINER_KAFKA" "$KAFKA_BIN/kafka-topics.sh" \\',
        '    --bootstrap-server "$BOOTSTRAP" --describe --topic "$t" 2>/dev/null || true)',
        '  parts=$(printf \'%s\\n\' "$desc" | ' + _PARTITION_AWK + ")",
        '  repl=$(printf \'%s\\n\' "$desc" | ' + _REPLICATION_AWK + ")",
        "  policy=$(printf '%s\\n' \"$desc\" \\",
        "    | sed -n 's/.*cleanup\\.policy=\\([a-z]*\\).*/\\1/p' | head -1)",
        '  [ -n "$parts" ] || parts=null',
        '  [ -n "$repl" ] || repl=null',
        '  [ "$first" -eq 1 ] || printf \',\'',
        "  first=0",
        '  printf \'\\n    {"name": "%s", "partitions": %s, "replication_factor": %s,'
        ' "cleanup_policy": "%s"}\' \\',
        '    "$t" "$parts" "$repl" "$policy"',
        "done",
        "printf '\\n  ],\\n'",
        "",
        "printf '  \"tables\": ['",
        "first=1",
        'for q in $TABLES; do',
        # ${q%%.*} is shell parameter expansion, not a printf escape: it strips
        # the longest '.'-suffix to leave the database name.
        "  db=${q%%.*}",
        "  tb=${q#*.}",
        '  cols=$(docker exec -i "$CONTAINER_CH" clickhouse-client --query \\',
        '    "SELECT arrayStringConcat(groupArray(name), \',\') FROM system.columns \\',
        "     WHERE database = '$db' AND table = '$tb'\" 2>/dev/null || true)",
        '  [ "$first" -eq 1 ] || printf \',\'',
        "  first=0",
        '  printf \'\\n    {"name": "%s", "columns": "%s"}\' "$q" "$cols"',
        "done",
        "printf '\\n  ]\\n'",
        "printf '}\\n'",
        "",
    ]
    return "\n".join(lines)


_INIT_README = """# Generated init jobs

`p09 render-init` wrote everything here from
`../../contracts/contracts.lock.yaml`. Do not edit these files: the next render
overwrites them, and a hand-edited init job is the drift they exist to prevent.

Run them where the Docker daemon is. On this machine that is inside WSL, so the
scripts reach the services through `docker exec` rather than over a socket --
WSL's localhost forwarding does not bridge 9092 or 8123 to Windows, and a script
that assumed it did would fail in a way that looks like a broken broker.

```sh
cd 09-full-system-integration/compose
docker compose -f compose.dev.yaml up -d      # wait for both healthchecks
sh init/01-topics.sh                          # create, then describe and decide
sh init/02-apply-ddl.sh                       # apply P05 + P06 DDL by path
sh init/03-verify.sh > /tmp/p09-infra.json    # observe only
```

Then, wherever `p09` is installed:

```sh
p09 verify-infra --observed /tmp/p09-infra.json
```

`03-verify.sh` reports and `verify-infra` judges, deliberately: a script that
decided its own verdict would be marking its own work.

Exit codes. `01-topics.sh` returns 1 if a topic has the wrong partition count or
a broker default re-enables auto-creation. `02-apply-ddl.sh` returns non-zero on
a missing file or a failed statement. `03-verify.sh` returns 0 whenever it
managed to observe -- including when what it observed is wrong, because that is a
verdict and verdicts are not its job.
"""


def render_init(lock: dict[str, Any], root: Path, out_dir: Path) -> list[Path]:
    """Write the init jobs derived from ``lock``; returns the paths written."""
    expect = InfraExpectation.from_lock(lock)
    out_dir.mkdir(parents=True, exist_ok=True)
    artifacts = {
        "01-topics.sh": _render_topics(lock, expect),
        "02-apply-ddl.sh": _render_ddl(lock, root),
        "03-verify.sh": _render_verify(lock, expect),
        "README.md": _INIT_README,
    }
    written: list[Path] = []
    for name, text in artifacts.items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


# --------------------------------------------------------------------------
# judging what the verify script observed
# --------------------------------------------------------------------------

@dataclass
class InfraFinding:
    subject: str
    verdict: str          # PASS | FAIL | INCONCLUSIVE
    detail: str

    def as_dict(self) -> dict[str, str]:
        return {
            "subject": self.subject,
            "verdict": self.verdict,
            "detail": self.detail,
        }


def parse_verify_report(text: str) -> dict[str, Any]:
    """Load the JSON the verify script emitted, refusing anything else."""
    try:
        document = json.loads(text)
    except json.JSONDecodeError as exc:
        raise DeployError("observation is not valid JSON: %s" % exc) from exc
    if not isinstance(document, dict):
        raise DeployError("observation must be a JSON object")
    return document


def _judge_topic(name: str, row: dict[str, Any] | None, expect: InfraExpectation) -> InfraFinding:
    if row is None:
        return InfraFinding(
            "topic " + name,
            "INCONCLUSIVE",
            "absent from the observation; the topic was never described",
        )
    partitions = row.get("partitions")
    if partitions is None:
        return InfraFinding(
            "topic " + name,
            "INCONCLUSIVE",
            "describe returned no partition count, so the topic may not exist",
        )
    if int(partitions) != expect.partitions_per_topic:
        return InfraFinding(
            "topic " + name,
            "FAIL",
            "partitions=%s, lock requires %d. Per-key ordering is scoped to a "
            "partition, so this changes the ordering contract."
            % (partitions, expect.partitions_per_topic),
        )
    policy = row.get("cleanup_policy") or ""
    if policy and policy != expect.cleanup_policy:
        return InfraFinding(
            "topic " + name,
            "FAIL",
            "cleanup.policy=%r, lock requires %r. Compaction drops superseded "
            "records per key, which would break replay."
            % (policy, expect.cleanup_policy),
        )
    return InfraFinding(
        "topic " + name,
        "PASS",
        "partitions=%s cleanup.policy=%s" % (partitions, policy or "broker default"),
    )


def _judge_table(name: str, row: dict[str, Any] | None) -> InfraFinding:
    if row is None:
        return InfraFinding("table " + name, "INCONCLUSIVE", "absent from the observation")
    columns = [c for c in str(row.get("columns") or "").split(",") if c]
    if not columns:
        return InfraFinding(
            "table " + name,
            "FAIL",
            "system.columns returned nothing, so the object does not exist",
        )
    return InfraFinding("table " + name, "PASS", "%d columns" % len(columns))


def compare_infra(
    lock: dict[str, Any], observed: dict[str, Any]
) -> tuple[list[InfraFinding], str]:
    """Check an observation against the lock. Returns findings and a verdict.

    A missing observation is ``INCONCLUSIVE``, never ``PASS``: P09 G2 cannot be
    satisfied by a check that did not run.
    """
    expect = InfraExpectation.from_lock(lock)
    topics = {
        row.get("name"): row
        for row in (observed.get("topics") or [])
        if isinstance(row, dict)
    }
    tables = {
        row.get("name"): row
        for row in (observed.get("tables") or [])
        if isinstance(row, dict)
    }
    findings = [_judge_topic(name, topics.get(name), expect) for name in expect.topics]
    findings.extend(_judge_table(name, tables.get(name)) for name in expect.tables)

    if any(f.verdict == "FAIL" for f in findings):
        verdict = "G2_NO_GO"
    elif any(f.verdict == "INCONCLUSIVE" for f in findings):
        verdict = "G2_INCONCLUSIVE"
    else:
        verdict = "G2_PASS"
    return findings, verdict


def infra_report(lock: dict[str, Any], observed: dict[str, Any]) -> dict[str, Any]:
    """The full comparison, ready to serialise next to the audit report."""
    findings, verdict = compare_infra(lock, observed)
    return {
        "generated_at_utc": _utc_now(),
        "observed_at_utc": observed.get("generated_at_utc"),
        "lock_cut_at_utc": lock.get("generated_at_utc"),
        "cluster_id": observed.get("cluster_id"),
        "clickhouse_version": observed.get("clickhouse_version"),
        "verdict": verdict,
        "findings": [f.as_dict() for f in findings],
    }
