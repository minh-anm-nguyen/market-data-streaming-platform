def _flatten(node: Any, prefix: str = "") -> dict[str, Any]:
    """Flatten nested maps and lists into ``dotted.path`` -> scalar."""
    out: dict[str, Any] = {}
    if isinstance(node, dict):
        if not node:
            out[prefix] = {}
            return out
        for key, value in node.items():
            out.update(_flatten(value, prefix + "." + str(key) if prefix else str(key)))
        return out
    if isinstance(node, list):
        if not node:
            out[prefix] = []
            return out
        for index, value in enumerate(node):
            out.update(_flatten(value, "%s[%d]" % (prefix, index)))
        return out
    out[prefix] = node
    return out


def verify_lock(locked: dict[str, Any], result: AuditResult) -> tuple[list[str], list[str]]:
    """Compare a stored lock against a fresh audit.

    Returns ``(drifted, notes)``. Only ``cross_project_identity`` counts as
    drift: ``per_build_identity`` is expected to vary by machine and toolchain,
    so a change there is reported as a note rather than as a failure.
    """
    fresh = build_lock(result)
    drifted: list[str] = []
    notes: list[str] = []

    old = _flatten(locked.get("cross_project_identity", {}))
    new = _flatten(fresh.get("cross_project_identity", {}))
    for key in sorted(set(old) | set(new)):
        if key not in old:
            drifted.append("added %s = %r" % (key, new[key]))
        elif key not in new:
            drifted.append("removed %s (was %r)" % (key, old[key]))
        elif old[key] != new[key]:
            drifted.append("changed %s: %r -> %r" % (key, old[key], new[key]))

    old_build = _flatten(locked.get("per_build_identity", {}))
    new_build = _flatten(fresh.get("per_build_identity", {}))
    for key in sorted(set(old_build) | set(new_build)):
        if old_build.get(key) != new_build.get(key):
            notes.append(
                "per-build %s: %r -> %r" % (key, old_build.get(key), new_build.get(key))
            )

    if locked.get("audit_verdict") != fresh.get("audit_verdict"):
        notes.append(
            "audit verdict moved: %s -> %s"
            % (locked.get("audit_verdict"), fresh.get("audit_verdict"))
        )
    return drifted, notes
