"""``contracts.lock.yaml``: the one place the cross-project contract is pinned.

P09 M0's deliverable. The lock is **generated from the projects**, never hand
written, so it cannot drift from them by being edited. Once generated it is the
reference: :func:`verify_lock` re-probes the tree and reports every value that
moved, which is what makes a contract change show up in CI as a diff rather than
in a run as corrupted data (P09 FR-05).

The lock records two kinds of thing, and keeping them apart is the point:

* **Cross-project identities** -- one value every project must share: the
  normalised schema digest, the topic names, the identity tuple, the bar width.
  A disagreement here is a blocker.
* **Per-build identities** -- values *expected* to differ per project, the
  descriptor digests above all. Recording them alongside the object each one
  hashes stops a future reader mistaking them for a shared identity and
  "fixing" the disagreement by copying one over the others.

A lock also carries the findings that were open when it was cut. A lock
recording only the agreements would read as a clean bill of health.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from . import yamlsub
from .audit import AuditResult
from .probes import PROJECT_DIRS, ProjectFacts

LOCK_VERSION = 1
LOCK_FILENAME = "contracts.lock.yaml"

_HEADER = [
    "contracts.lock.yaml -- generated by `p09 contracts-lock`. Do not hand-edit.",
    "",
    "P09 M0. Every value below was read out of the project that owns it; the",
    "provenance for each one is in reports/audit.json.",
    "",
    "cross_project_identity   values every project MUST share. A mismatch is a",
    "                         blocker: run `p09 contracts-verify` to see which.",
    "per_build_identity       values expected to DIFFER per project. Do not",
    "                         reconcile these by copying one over the others;",
    "                         read open_findings P09-M0-03 first.",
]


def _facts_table(facts: ProjectFacts, keys: tuple[str, ...]) -> dict[str, Any]:
    """Pin the named facts of one project, preserving unknowns as nulls."""
    out: dict[str, Any] = {}
    for key in keys:
        fact = facts.facts.get(key)
        if fact is None:
            out[key] = None
        elif fact.known:
            out[key] = fact.value
        else:
            out[key] = None
            out[key + "__unknown_reason"] = fact.unknown_reason
    return out


def build_lock(result: AuditResult) -> dict[str, Any]:
    """Assemble the lock document from a completed audit."""
    facts = result.facts

    def get(project: str, key: str) -> Any:
        pf = facts.get(project)
        return pf.get(key) if pf else None

    schema = result.wire_schema

    cross: dict[str, Any] = {
        "wire_schema": {
            "package": schema.get("package"),
            "syntax": schema.get("syntax"),
            "canonical_path": schema.get("canonical_path"),
            "canonical_file_sha256": schema.get("canonical_file_sha256"),
            # This, not a descriptor digest, is the contract identity.
            "normalized_sha256": schema.get("normalized_sha256"),
            "normalized_by": "p09_integration.protoparse canonical_text v1",
            "copies": [
                {
                    "project": c["project"],
                    "path": c["path"],
                    "file_sha256": c["file_sha256"],
                    "matches_canonical": c["matches_canonical"],
                }
                for c in schema.get("copies", [])
            ],
        },
        "identity": {
            "event_identity": get("P05", "event_identity") or get("P01", "event_identity"),
            "semantic_digest": get("P05", "semantic_digest"),
            "source_schema_version": get("P01", "source_schema_version"),
        },
        "transport": {
            "p01_jsonl_tcp": {
                "host": get("P01", "tcp_host"),
                "port": get("P01", "tcp_port"),
                "framing": get("P01", "wire_framing"),
            },
            "p02_mdp1_tcp": {
                "port": get("P02", "mdp1_tcp_port"),
                "magic": get("P02", "mdp1_magic"),
                "length_prefix": "uint32_be",
                "max_payload_bytes": get("P02", "max_payload_bytes"),
            },
            "kafka_record_value": {
                "framing": get("P02", "kafka_value_framing"),
                "forbidden_prefixes": ["MDP1", "uint32_be_length"],
            },
        },
        "kafka": {
            "ticks_topic": get("P04", "ticks_topic"),
            "quotes_topic": get("P04", "quotes_topic"),
            "record_key": get("P04", "record_key"),
            "partitions_per_topic": get("P04", "partitions_per_topic"),
            "partitioner": get("P04", "partitioner"),
            "cleanup_policy": get("P04", "cleanup_policy"),
            "allow_auto_topic_create": get("P04", "allow_auto_topic_create"),
            "max_record_value_bytes": get("P04", "max_kafka_value_bytes"),
            "max_key_bytes": get("P04", "max_key_bytes"),
            "consumer_group": get("P05", "group_id"),
            # P09 should issue this; see open finding P09-M0-08.
            "topic_generation": get("P05", "topic_generation"),
        },
        "clickhouse": {
            "raw_table": "%s.%s" % (get("P05", "ch_database"), get("P05", "ch_table")),
            "canonical_table": get("P06", "canonical_table"),
            "bars_table": get("P06", "bars_table"),
            "bar_interval_ns": get("P06", "bar_interval_ns"),
            "timezone": get("P06", "timezone"),
        },
        "semantics": {
            "delivery": get("P05", "delivery_semantics"),
            "raw_physical_duplicates_allowed": True,
            "canonical_duplicates_allowed": False,
            "note": (
                "at-least-once: physical duplicate rows in the raw table are "
                "expected and must be reported, never counted as two business "
                "events. Logical idempotency belongs to the query layer."
            ),
        },
    }

    per_build: dict[str, Any] = {
        "descriptor_digests": {
            "policy": "PER_BUILD_SELF_CHECK_NOT_CROSS_PROJECT",
            "cross_project_identity_is": (
                "cross_project_identity.wire_schema.normalized_sha256"
            ),
            "observed": [
                {
                    "project": project,
                    "value": (
                        get("P02", "descriptor_sha256")
                        if project == "P02"
                        else get(project, "descriptor_pin")
                    ),
                    "hashed_object": get(project, "descriptor_digest_object"),
                }
                for project in ("P02", "P03", "P04", "P05")
                if project in facts
            ],
        },
        "toolchains": {
            "P02": (
                _facts_table(
                    facts["P02"],
                    (
                        "protoc_version",
                        "cpp_protobuf_runtime",
                        "python_protobuf_runtime",
                        "python_version",
                        "cxx_compiler",
                    ),
                )
                if "P02" in facts
                else {}
            ),
            "P03": {"protobuf_root": get("P03", "protobuf_root")},
        },
    }

    projects = [
        {
            "id": project,
            "directory": PROJECT_DIRS[project],
            "role": facts[project].role if project in facts else None,
            "present": facts[project].present if project in facts else False,
        }
        for project in PROJECT_DIRS
    ]

    open_findings = [
        {
            "id": f.id,
            "severity": f.severity,
            "verdict": f.verdict,
            "gate": f.gate,
            "milestone": f.milestone,
            "title": f.title,
        }
        for f in result.findings
        if f.verdict != "PASS"
    ]

    return {
        "lock_version": LOCK_VERSION,
        "generated_at_utc": result.generated_at_utc,
        "generated_by": "p09 contracts-lock",
        "audit_verdict": result.verdict,
        "projects": projects,
        "cross_project_identity": cross,
        "per_build_identity": per_build,
        "open_findings": open_findings,
    }


def render_lock(document: dict[str, Any]) -> str:
    """The lock as text, including its header. Writing it is a separate step."""
    return yamlsub.dumps(document, header=_HEADER)


def write_lock(path: Path, document: dict[str, Any]) -> str:
    """Render and write the lock; returns the text that was written."""
    text = render_lock(document)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return text


def load_lock(path: Path) -> dict[str, Any]:
    """Read a lock, failing loudly on an unexpected version."""
    document = yamlsub.loads(path.read_text(encoding="utf-8"))
    version = document.get("lock_version")
    if version != LOCK_VERSION:
        raise ValueError(
            "lock_version %r is not supported by this build (expected %d)"
            % (version, LOCK_VERSION)
        )
    return document


