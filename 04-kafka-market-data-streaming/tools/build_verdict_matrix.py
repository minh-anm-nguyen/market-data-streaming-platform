#!/usr/bin/env python3
"""Build tests/expected/what_if_verdicts.yaml from section 9 of the design.

The 280 case ids, priorities and stimuli are parsed out of the design document
rather than retyped, for two reasons: a retyped matrix drifts from the document
it claims to track, and a hand-written one can quietly omit the cases nobody got
to. Parsing means every case in the document appears in the matrix, and anything
not explicitly claimed defaults to NOT_RUN.

Statuses, and what each one is allowed to mean (section 14 report rules):

  PASS             the case oracle was satisfied: the stimulus was applied, an
                   independent oracle checked the result, and an artifact exists
  PASS_MODEL_ONLY  the stimulus was applied to the in-process fake transport and
                   the assertion held, but this case oracle calls for a real
                   broker. This is NOT a pass for the case. It is recorded
                   separately so the gap stays visible instead of flattering
  FAIL             the stimulus was applied and the behaviour was wrong
  INCOMPLETE       the run could not finish, or completeness is unprovable
  INCONCLUSIVE     the stimulus could not be demonstrably applied
  NOT_RUN          not attempted
  BLOCKED          cannot be attempted in this lab, with the reason stated

The claims below are deliberately conservative. A case is PASS only when the
evidence named in `evidence` actually exercises what the case describes.
"""

