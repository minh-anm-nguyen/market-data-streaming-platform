GROUP_HEADING = re.compile(r"^### ([A-T])\. (.+?) \((\d+)\)\s*$")
CASE_ROW = re.compile(
    r"^\|\s*\*\*([A-T]-\d{2})\*\*\s*\|\s*`(P\d)`\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*$"
)


def yaml_quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    parser = argparse.ArgumentParser(description="build the what-if verdict matrix")
    parser.add_argument(
        "--design",
        default="../docs/PROJECT_04_Kafka_Market_Data_Streaming_System_Design.md",
        help="the design document holding section 9",
    )
    parser.add_argument("--out", default="tests/expected/what_if_verdicts.yaml")
    args = parser.parse_args()

    design_path = Path(args.design)
    if not design_path.exists():
        print(f"design document not found: {design_path}")
        return 2
    lines = design_path.read_text(encoding="utf-8").splitlines()

    groups: List[Dict[str, object]] = []
    current: Optional[Dict[str, object]] = None
    for line in lines:
        heading = GROUP_HEADING.match(line)
        if heading:
            current = {
                "letter": heading.group(1),
                "scope": heading.group(2),
                "declared_count": int(heading.group(3)),
                "cases": [],
            }
            groups.append(current)
            continue
        if current is None:
            continue
        row = CASE_ROW.match(line)
        if row:
            cases = current["cases"]
            assert isinstance(cases, list)
            cases.append(
                {
                    "id": row.group(1),
                    "priority": row.group(2),
                    "stimulus": row.group(3),
                    "expected": row.group(4),
                    "oracle": row.group(5),
                }
            )

    total = sum(len(g["cases"]) for g in groups)  # type: ignore[arg-type]
    if total == 0:
        print("parsed no cases; the document format may have changed")
        return 2

    status_counts: Dict[str, int] = {}
    out: List[str] = []
    out.append("# Project 04 what-if verdict matrix.")
    out.append("#")
    out.append("# GENERATED by tools/build_verdict_matrix.py from section 9 of the design")
    out.append("# document. Case ids, priorities and stimuli are parsed from the document, so")
    out.append("# this file cannot silently omit a case or drift from the text it tracks.")
    out.append("#")
    out.append("# Status vocabulary, and what each one is allowed to mean:")
    out.append("#")
    out.append("#   PASS             the case oracle was satisfied: the stimulus was applied,")
    out.append("#                    an independent oracle checked it, an artifact exists")
    out.append("#   PASS_MODEL_ONLY  the stimulus was applied to the in-process fake transport")
    out.append("#                    and the assertion held, but this case oracle calls for a")
    out.append("#                    real broker. This is NOT a pass for the case; it is")
    out.append("#                    recorded separately so the gap stays visible")
    out.append("#   FAIL             the stimulus was applied and the behaviour was wrong")
    out.append("#   INCOMPLETE       the run could not finish, or completeness is unprovable")
    out.append("#   INCONCLUSIVE     the stimulus could not be demonstrably applied")
    out.append("#   NOT_RUN          not attempted")
    out.append("#   BLOCKED          cannot be attempted in this lab, with the reason stated")
    out.append("#")
    out.append("# Section 14 rule: no case may be marked PASS because nothing crashed.")
    out.append("")
    out.append("matrix_version: 1")
    out.append(f"design_document: {yaml_quote(design_path.name)}")
    out.append(f"cases_parsed: {total}")
    out.append("groups:")

    for group in groups:
        cases = group["cases"]
        assert isinstance(cases, list)
        out.append(f"  - letter: {group['letter']}")
        out.append(f"    scope: {yaml_quote(str(group['scope']))}")
        out.append(f"    declared_count: {group['declared_count']}")
        out.append(f"    parsed_count: {len(cases)}")
        out.append("    cases:")
        for case in cases:
            claim = CLAIMS.get(case["id"], {"status": "NOT_RUN"})
            status = claim["status"]
            status_counts[status] = status_counts.get(status, 0) + 1
            out.append(f"      - id: {case['id']}")
            out.append(f"        priority: {case['priority']}")
            out.append(f"        status: {status}")
            out.append(f"        stimulus: {yaml_quote(str(case['stimulus']))}")
            out.append(f"        expected: {yaml_quote(str(case['expected']))}")
            out.append(f"        oracle: {yaml_quote(str(case['oracle']))}")
            if "evidence" in claim:
                out.append(f"        evidence: {yaml_quote(claim['evidence'])}")
            if "note" in claim:
                out.append(f"        note: {yaml_quote(claim['note'])}")

    out.append("")
    out.append("scenarios:")
    for scenario_id, claim in SCENARIOS.items():
        out.append(f"  - id: {scenario_id}")
        out.append(f"    status: {claim['status']}")
        if "evidence" in claim:
            out.append(f"    evidence: {yaml_quote(claim['evidence'])}")
        if "note" in claim:
            out.append(f"    note: {yaml_quote(claim['note'])}")

    out.append("")
    out.append("summary:")
    for status in sorted(status_counts):
        out.append(f"  {status}: {status_counts[status]}")
    out.append(f"  total: {total}")

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")

    print(f"wrote {args.out}")
    print(f"cases parsed: {total}")
    for status in sorted(status_counts):
        print(f"  {status}: {status_counts[status]}")
    parsed_ids = {c["id"] for g in groups for c in g["cases"]}  # type: ignore[union-attr]
    unknown_claims = sorted(set(CLAIMS) - parsed_ids)
    if unknown_claims:
        print(f"WARNING: claims for ids not present in the document: {unknown_claims}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
